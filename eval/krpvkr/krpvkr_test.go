	require.NotEmpty(t, draws)

	winRecall /= float64(len(wins))
	drawRecall /= float64(len(draws))

	auc := 0.0
	for _, w := range wins {
		for _, d := range draws {
			switch {
			case w > d:
				auc++
			case w == d:
				auc += 0.5
			}
		}
	}
	auc /= float64(len(wins) * len(draws))

	meanW := 0.0
	for _, s := range wins {
		meanW += s
	}
	meanW /= float64(len(wins))

	meanD := 0.0
	for _, s := range draws {
		meanD += s
	}
	meanD /= float64(len(draws))

	assert.GreaterOrEqual(t, auc, 0.88, "AUC(W,D)")
