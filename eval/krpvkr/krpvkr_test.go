	var winRecall, drawRecall float64

	for _, tt := range tests {
		b := Must(board.FromFEN(tt.fen))
		got := ScaleFactor[float64](b)

		if tt.draw {
			draws = append(draws, got)
			if got < threshold {
				drawRecall++
			}
		} else {
			wins = append(wins, got)
			if got >= threshold {
				winRecall++
			}
		}
	}

