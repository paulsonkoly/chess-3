func TestFeatures(t *testing.T) {
	tests := []struct {
		name string
		fen  string
		want [featureCount]feature
	}{
		{
			name: "white strong canonical",
			fen:  "8/8/5k2/7r/3P4/2K5/R7/8 w - - 0 1",
			want: [featureCount]feature{3, 3, 0, -1, -1, -3, -2, 2, 2, 4, 1, 4, 1, 0, 0, 0, 5, 2, 1, 2},
		},
		{
			name: "black strong h pawn mirrored",
			fen:  "8/8/6k1/7p/7r/R7/K7/8 w - - 0 1",
			want: [featureCount]feature{0, 3, 1, 1, -1, 0, 1, 7, 3, 7, 2, 5, 4, 0, 0, 0, 5, 7, 1, 7},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			b := Must(board.FromFEN(tt.fen))

			got := features(b)
			assert.Equal(t, tt.want, got, "fen %s", tt.fen)
		})
	}
}

